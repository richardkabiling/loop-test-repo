#!/usr/bin/env bash
# sync-agent-files.sh: emit tool-specific agent files from one canonical source.
#
#   .agents/skills/<name>/      -> .claude/skills/<name>  (relative symlink; --copy to copy instead)
#   .agents/rules/<name>.md     -> .claude/rules/<name>.md       (Claude Code, `paths:` frontmatter)
#                               -> .cursor/rules/<name>.mdc      (Cursor, `globs:` frontmatter)
#                               -> <dir>/AGENTS.md rule block    (Codex + every AGENTS.md reader)
#                               -> <dir>/CLAUDE.md "@AGENTS.md"  (only if missing; Claude Code)
#   REVIEW.md (sdlc:review-core) -> AGENTS.md "## Review guidelines" block (Codex review, local /code-review)
#                               -> .cursor/BUGBOT.md                 (Cursor Bugbot; full copy)
#
# Usage: sync-agent-files.sh [--root DIR] [--tools LIST] [--dry-run | --check] [--copy] [--help]
#   --tools LIST  comma list of claude-code,cursor,codex (default: "tools" in docs/sdlc/loop.json,
#                 else all three)
#   --dry-run     print what would change; write nothing
#   --check       exit 1 if anything is out of sync (for CI and check-loop.sh); write nothing
#   --copy        copy skills into .claude/skills instead of symlinking (Windows without symlinks)
#
# Rule source format (.agents/rules/<name>.md):
#   ---
#   paths: ["src/gen/**"]          # or a YAML list; required
#   description: "One line"        # optional (Cursor uses it)
#   protect: true | existing       # optional: protect-paths.sh blocks edits (existing = only existing files)
#   agents_dir: "packages/api"     # optional: folder whose AGENTS.md gets the rule block
#   ---
#   Default agents_dir: the globs' longest literal directory prefix; for protected rules, its
#   parent, so generators that wipe a folder (codegen, migrations) never delete the AGENTS.md.
#   Rule body (1-5 lines).
#
# Idempotent. Generated files carry a marker; stale generated files and blocks are removed.
# Exit codes: 0 ok / in sync, 1 out of sync (--check), 2 usage error.
set -euo pipefail

ROOT="."; TOOLS=""; MODE="write"; COPY=0
while [ $# -gt 0 ]; do
  case "$1" in
    --root) ROOT="${2:?}"; shift 2 ;;
    --tools) TOOLS="${2:?}"; shift 2 ;;
    --dry-run) MODE="dry"; shift ;;
    --check) MODE="check"; shift ;;
    --copy) COPY=1; shift ;;
    -h|--help) sed -n '2,35p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "sync-agent-files: unknown argument '$1' (try --help)" >&2; exit 2 ;;
  esac
done
cd "$ROOT" || { echo "sync-agent-files: cannot cd to '$ROOT'" >&2; exit 2; }

if [ -z "$TOOLS" ]; then
  if [ -f docs/sdlc/loop.json ]; then
    TOOLS="$(tr -d '\n' < docs/sdlc/loop.json | grep -oE '"tools"[[:space:]]*:[[:space:]]*\[[^]]*\]' | grep -oE '"(claude-code|cursor|codex)"' | tr -d '"' | paste -sd, - || true)"
  fi
  [ -n "$TOOLS" ] || TOOLS="claude-code,cursor,codex"
fi
has_tool() { case ",$TOOLS," in *",$1,"*) return 0 ;; *) return 1 ;; esac; }

MARK="generated by scripts/sdlc/sync-agent-files.sh"
DRIFT=0
note() { echo "$1" >&2; }

# write_file PATH CONTENT: create/update a file according to MODE.
write_file() {
  local path="$1" content="$2"
  if [ -f "$path" ] && [ "$(cat "$path")" = "$content" ]; then return 0; fi
  DRIFT=1
  case "$MODE" in
    write) mkdir -p "$(dirname "$path")"; printf '%s\n' "$content" > "$path"; note "wrote   $path" ;;
    dry)   note "would write $path" ;;
    check) note "out of sync: $path" ;;
  esac
}
remove_file() {
  DRIFT=1
  case "$MODE" in
    write) rm -f "$1"; note "removed $1" ;;
    dry)   note "would remove $1" ;;
    check) note "stale: $1" ;;
  esac
}

# --- frontmatter parser: prints "key<TAB>value", "path<TAB>glob" and "body<TAB>line" records
parse_rule() {
  awk '
    function trim(s){ sub(/^[ \t]+/,"",s); sub(/[ \t]+$/,"",s); if (s ~ /^".*"$/ || s ~ /^'\''.*'\''$/) s=substr(s,2,length(s)-2); return s }
    NR==1 && /^---[ \t]*$/ { fm=1; next }
    fm==1 && /^---[ \t]*$/ { fm=2; next }
    fm==1 {
      if ($0 ~ /^paths:[ \t]*\[/) { s=$0; sub(/^paths:[ \t]*\[/,"",s); sub(/\][ \t]*$/,"",s); n=split(s,a,","); for(i=1;i<=n;i++){ g=trim(a[i]); if(g!="") print "path\t" g }; inp=0; next }
      if ($0 ~ /^paths:[ \t]*$/) { inp=1; next }
      if (inp && $0 ~ /^[ \t]*-[ \t]*/) { g=$0; sub(/^[ \t]*-[ \t]*/,"",g); print "path\t" trim(g); next }
      inp=0
      if (match($0, /^[A-Za-z_-]+:/)) { k=substr($0,1,RLENGTH-1); v=substr($0,RLENGTH+1); print k "\t" trim(v) }
      next
    }
    fm==2 { print "body\t" $0 }
  ' "$1"
}

# Longest literal directory prefix shared by all globs ("." when none).
root_dir() {
  awk '
    { n=split($0, s, "/"); lit=""; for(i=1;i<=n;i++){ if (s[i] ~ /[*?[{]/) break; if (i==n) break; lit = lit (lit==""?"":"/") s[i] }
      if (NR==1) pre=lit; else { split(pre,p,"/"); split(lit,q,"/"); c=""; for(j=1; (j in p) && (j in q) && p[j]==q[j]; j++) c = c (c==""?"":"/") p[j]; pre=c } }
    END { print (pre=="" ? "." : pre) }'
}

# Replace or append a marked block in a file's content (stdin = current content).
upsert_block() { # $1 name, $2 block text
  awk -v name="$1" -v block="$2" '
    BEGIN { start="<!-- sdlc:rule " name " "; stop="<!-- /sdlc:rule " name " -->" }
    index($0, start)==1 { skip=1; if (!done) { print block; done=1 }; next }
    skip && $0==stop { skip=0; next }
    skip { next }
    { print }
    END { if (!done) { print ""; print block } }'
}
remove_block() { # $1 name
  awk -v name="$1" 'BEGIN{ start="<!-- sdlc:rule " name " "; stop="<!-- /sdlc:rule " name " -->" }
    index($0,start)==1 { skip=1; next } skip && $0==stop { skip=0; next } skip { next } { print }'
}

# ---------------------------------------------------------------- skills
if has_tool claude-code && [ -d .agents/skills ]; then
  for src in .agents/skills/*/; do
    [ -f "${src}SKILL.md" ] || continue
    name="$(basename "$src")"; dst=".claude/skills/$name"; target="../../.agents/skills/$name"
    if [ "$COPY" -eq 1 ]; then
      if [ -L "$dst" ] || ! diff -rq "$src" "$dst" >/dev/null 2>&1; then
        DRIFT=1
        case "$MODE" in
          write) rm -rf "$dst"; mkdir -p .claude/skills; cp -R "$src" "$dst"; note "copied  $dst" ;;
          *) note "out of sync: $dst" ;;
        esac
      fi
    elif [ "$(readlink "$dst" 2>/dev/null || true)" != "$target" ]; then
      if [ -e "$dst" ] && [ ! -L "$dst" ]; then
        note "skip    $dst exists and is not a symlink (a hand-written skill?). Remove it or rename the source."
        continue
      fi
      DRIFT=1
      case "$MODE" in
        write) mkdir -p .claude/skills; ln -sfn "$target" "$dst"; note "linked  $dst -> $target" ;;
        *) note "out of sync: $dst" ;;
      esac
    fi
  done
  # remove dangling symlinks that point into .agents/skills
  for l in .claude/skills/*; do
    [ -L "$l" ] || continue
    case "$(readlink "$l")" in ../../.agents/skills/*) [ -e "$l" ] || remove_file "$l" ;; esac
  done
fi

# ---------------------------------------------------------------- rules
RULE_NAMES=" "
if [ -d .agents/rules ]; then
  for src in .agents/rules/*.md; do
    [ -f "$src" ] || continue
    name="$(basename "$src" .md)"; RULE_NAMES="$RULE_NAMES$name "
    rec="$(parse_rule "$src")"
    globs="$(printf '%s\n' "$rec" | awk -F'\t' '$1=="path"{print $2}')"
    if [ -z "$globs" ]; then note "skip    $src has no paths: frontmatter"; continue; fi
    desc="$(printf '%s\n' "$rec" | awk -F'\t' '$1=="description"{print $2; exit}')"
    body="$(printf '%s\n' "$rec" | awk 'index($0,"body\t")==1{print substr($0,6)}' | sed -e '/./,$!d')"
    [ -n "$desc" ] || desc="$(printf '%s\n' "$body" | head -n1 | cut -c1-120)"
    yaml_paths="$(printf '%s\n' "$globs" | sed 's/.*/  - "&"/')"
    globs_csv="$(printf '%s\n' "$globs" | paste -sd, -)"
    globs_md="$(printf '%s\n' "$globs" | sed 's/.*/`&`/' | paste -sd, - | sed 's/,/, /g')"

    if has_tool claude-code; then
      write_file ".claude/rules/$name.md" "---
paths:
$yaml_paths
---
<!-- $MARK from .agents/rules/$name.md; edit the source -->
$body"
    fi
    if has_tool cursor; then
      write_file ".cursor/rules/$name.mdc" "---
description: $desc
globs: $globs_csv
alwaysApply: false
---
<!-- $MARK from .agents/rules/$name.md; edit the source -->
$body"
    fi
    # AGENTS.md block: read by Codex, Cursor and Claude Code (when no CLAUDE.md sits beside it)
    dir="$(printf '%s\n' "$rec" | awk -F'\t' '$1=="agents_dir"{print $2; exit}')"
    if [ -z "$dir" ]; then
      dir="$(printf '%s\n' "$globs" | root_dir)"
      protect="$(printf '%s\n' "$rec" | awk -F'\t' '$1=="protect"{print $2; exit}')"
      if [ -n "$protect" ] && [ "$protect" != "false" ] && [ "$dir" != "." ]; then
        case "$dir" in */*) dir="${dir%/*}" ;; *) dir="." ;; esac
      fi
    fi
    dir="${dir%/}"; [ -n "$dir" ] || dir="."
    agents="$dir/AGENTS.md"; [ "$dir" = "." ] && agents="AGENTS.md"
    block="<!-- sdlc:rule $name (generated from .agents/rules/$name.md) -->
### When editing $globs_md
$body
<!-- /sdlc:rule $name -->"
    if [ -f "$agents" ]; then current="$(cat "$agents")"
    else current="# Agent notes for \`$dir/\`

Rules for this folder. Each block is generated from \`.agents/rules/\`; edit the source and run \`scripts/sdlc/sync-agent-files.sh\`."
    fi
    write_file "$agents" "$(printf '%s\n' "$current" | upsert_block "$name" "$block")"
    if has_tool claude-code && [ "$dir" != "." ] && [ ! -f "$dir/CLAUDE.md" ]; then
      write_file "$dir/CLAUDE.md" "@AGENTS.md"
    fi
  done
fi

# ---------------------------------------------------------------- review policy
if [ -f REVIEW.md ]; then
  core="$(awk '/<!-- sdlc:review-core -->/{f=1;next} /<!-- \/sdlc:review-core -->/{f=0} f' REVIEW.md)"
  if [ -n "$core" ] && [ -f AGENTS.md ]; then
    rblock="<!-- sdlc:review-guidelines (generated from REVIEW.md) -->
## Review guidelines

$core

Full policy: \`REVIEW.md\`.
<!-- /sdlc:review-guidelines -->"
    newagents="$(awk -v block="$rblock" '
      index($0,"<!-- sdlc:review-guidelines ")==1 { skip=1; if(!done){ print block; done=1 }; next }
      skip && $0=="<!-- /sdlc:review-guidelines -->" { skip=0; next }
      skip { next }
      !done && $0=="## Scoped rules" { print block; print ""; done=1 }
      { print }
      END { if(!done){ print ""; print block } }' AGENTS.md)"
    write_file AGENTS.md "$newagents"
  fi
  if has_tool cursor; then
    if [ -f .cursor/BUGBOT.md ] && ! grep -q "$MARK" .cursor/BUGBOT.md; then
      note "skip    .cursor/BUGBOT.md is hand-written; merge REVIEW.md into it, or delete it to have it generated"
    else
      write_file .cursor/BUGBOT.md "<!-- $MARK from REVIEW.md; edit the source -->
$(cat REVIEW.md)"
    fi
  fi
fi

# stale generated rule files and blocks
for f in .claude/rules/*.md .cursor/rules/*.mdc; do
  [ -f "$f" ] || continue
  grep -q "$MARK" "$f" || continue
  n="$(basename "$f")"; n="${n%.md}"; n="${n%.mdc}"
  case "$RULE_NAMES" in *" $n "*) ;; *) remove_file "$f" ;; esac
done
if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  AGENT_FILES="$( (git ls-files -co --exclude-standard -- 'AGENTS.md' '**/AGENTS.md' 2>/dev/null; [ -f AGENTS.md ] && echo AGENTS.md) | sort -u)"
else
  AGENT_FILES="$(find . -name AGENTS.md -not -path '*/node_modules/*' 2>/dev/null | sed 's#^\./##')"
fi
for a in $AGENT_FILES; do
  [ -f "$a" ] || continue
  for n in $(grep -oE '<!-- sdlc:rule [a-z0-9-]+ ' "$a" | awk '{print $3}'); do
    case "$RULE_NAMES" in *" $n "*) ;; *) write_file "$a" "$(remove_block "$n" < "$a")" ;; esac
  done
done

if [ "$MODE" = "check" ] && [ "$DRIFT" -eq 1 ]; then
  echo "sync-agent-files: out of sync. Run scripts/sdlc/sync-agent-files.sh" >&2
  exit 1
fi
[ "$DRIFT" -eq 0 ] && echo "sync-agent-files: in sync" >&2
exit 0
