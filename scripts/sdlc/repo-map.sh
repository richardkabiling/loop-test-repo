#!/usr/bin/env bash
# repo-map.sh: a budgeted map of the repo's source files and their top-level symbols (Markdown).
#
# A lightweight code graph for agents without LSP/MCP code intelligence (or for a cheap first read).
# Files are ranked by how many other files reference them (an import/mention count, like a crude
# PageRank), then listed with their top-level symbols (exports, functions, classes, types), and the
# output is trimmed to --max-lines. Inspired by Aider's repo map (tree-sitter + PageRank, ~1k tokens):
# https://github.com/Aider-AI/aider/blob/main/aider/website/docs/repomap.md
#
# Usage: repo-map.sh [--root DIR] [--max-lines N] [--write PATH] [--help]
#   --max-lines  output budget (default 150 lines, roughly 1-1.5k tokens)
#   --write      also write the map to PATH (e.g. docs/sdlc/REPO_MAP.md)
# Languages: JS/TS, Python, Go, Rust, Java/Kotlin, Ruby, C#. Bash 3.2 compatible. Read-only unless --write.
set -uo pipefail

ROOT="."; MAXL=150; OUT=""
while [ $# -gt 0 ]; do
  case "$1" in
    --root) ROOT="${2:?}"; shift 2 ;;
    --max-lines) MAXL="${2:?}"; shift 2 ;;
    --write) OUT="${2:?}"; shift 2 ;;
    -h|--help) sed -n '2,14p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "repo-map: unknown argument '$1'" >&2; exit 2 ;;
  esac
done
cd "$ROOT" || exit 2

if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then FILES="$(git ls-files -co --exclude-standard)"
else FILES="$(find . -type f -not -path '*/node_modules/*' -not -path './.git/*' | sed 's#^\./##')"; fi
SRC="$(printf '%s\n' "$FILES" | grep -E '\.(js|jsx|mjs|cjs|ts|tsx|py|go|rs|java|kt|rb|cs)$' \
  | grep -vE '(^|/)(node_modules|vendor|third_party|dist|build|gen|generated|__generated__)/|\.min\.js$|\.d\.ts$|_pb2\.py$|\.pb\.go$' | head -n 3000)"
[ -n "$SRC" ] || { echo "repo-map: no source files found" >&2; exit 0; }

TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
printf '%s\n' "$SRC" > "$TMP/src"

# rank: count of other source files mentioning the module's base name (without extension)
while IFS= read -r f; do
  b="$(basename "$f")"; m="${b%.*}"
  case "$m" in index|main|mod|__init__|lib|app) m="$(basename "$(dirname "$f")")/$m" ;; esac
  n=$(tr '\n' '\0' < "$TMP/src" | xargs -0 grep -lF -- "$m" 2>/dev/null | grep -vxF -- "$f" | wc -l | tr -d ' ')
  printf '%s\t%s\n' "$n" "$f"
done < "$TMP/src" | sort -t$'\t' -k1,1nr -k2,2 > "$TMP/ranked"

symbols() {
  case "$1" in
    *.js|*.jsx|*.mjs|*.cjs|*.ts|*.tsx)
      grep -oE '^export (default )?(async )?(function\*?|class|const|let|interface|type|enum) +[A-Za-z0-9_$]+' "$1" | awk '{print $NF}' ;;
    *.py)  grep -oE '^(async )?(def|class) +[A-Za-z0-9_]+' "$1" | awk '{print $NF}' ;;
    *.go)  grep -oE '^(func( \([^)]*\))?|type) +[A-Z][A-Za-z0-9_]*' "$1" | awk '{print $NF}' ;;
    *.rs)  grep -oE '^pub (async )?(fn|struct|enum|trait|type|mod) +[A-Za-z0-9_]+' "$1" | awk '{print $NF}' ;;
    *.java|*.kt|*.cs) grep -oE '^(public |internal )?(abstract |data |sealed |static )*(class|interface|enum|object|record) +[A-Za-z0-9_]+' "$1" | awk '{print $NF}' ;;
    *.rb)  grep -oE '^ *(class|module|def) +[A-Za-z0-9_:.?!]+' "$1" | awk '{print $NF}' ;;
  esac 2>/dev/null | awk '!seen[$0]++' | head -n 12 | paste -sd, - | sed 's/,/, /g'
}

{
  echo "# Repo map"
  echo
  echo "Generated by \`scripts/sdlc/repo-map.sh\` ($(wc -l < "$TMP/src" | tr -d ' ') source files; ranked by inbound references; budget $MAXL lines). Regenerate after structural changes; don't edit by hand."
  echo
  used=4
  while IFS=$'\t' read -r n f; do
    [ "$used" -ge "$MAXL" ] && { echo "- … $(( $(wc -l < "$TMP/ranked") - used + 4 )) more files not shown"; break; }
    s="$(symbols "$f")"
    if [ -n "$s" ]; then echo "- \`$f\` (refs $n): $s"; else echo "- \`$f\` (refs $n)"; fi
    used=$((used + 1))
  done < "$TMP/ranked"
} > "$TMP/map.md"

cat "$TMP/map.md"
if [ -n "$OUT" ]; then mkdir -p "$(dirname "$OUT")"; cp "$TMP/map.md" "$OUT"; echo "repo-map: wrote $OUT" >&2; fi
